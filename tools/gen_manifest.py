"""Writes ironbrigade_manifest.toml and runs ReXGlue codegen until it stops reporting
unresolved branch targets (adapted from F:/FromDustDeck/tools/gen_manifest.py).

Iron Brigade (XBLA, title 58410A95) is a single default.xex with no extra XEX modules.
Each unresolved branch target codegen reports becomes a function hint (size unknown: 0, codegen
finds the end). Hints live in tools/hints/default.txt ("0xADDR [0xSIZE]" per line).

    python tools/gen_manifest.py [--rexglue PATH] [--max-rounds N] [--no-codegen]
"""
import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_REXGLUE = ROOT / "build/sdk-install/bin/rexglue.exe"

# Register-as-local codegen, as in From Dust and PGR4Native (-17.9 % frame time measured there).
OPTIONS = {
    "cr_as_local": True,
    "ctr_as_local": True,
    "xer_as_local": True,
    "non_volatile_as_local": True,
    "reserved_as_local": True,
}


def hints_path():
    return ROOT / "tools" / "hints" / "default.txt"


def load_hints():
    hints = {}
    p = hints_path()
    if p.exists():
        for line in p.read_text().splitlines():
            parts = line.split("#")[0].split()
            if parts:
                hints[int(parts[0], 16)] = int(parts[1], 16) if len(parts) > 1 else 0
    return hints


def save_hints(hints):
    p = hints_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("".join(f"0x{a:08X} 0x{s:X}\n" for a, s in sorted(hints.items())))


def write_manifest():
    out = [
        "# ReXGlue codegen manifest for Iron Brigade (Xbox Live Arcade, title 58410A95).",
        "# Generated by tools/gen_manifest.py from tools/hints/; edit those, not this file.",
        "",
        "[project]",
        'name = "ironbrigade"',
        'sdk_version = "0.11.0"',
        'game_root = "game-data"',
        "",
        "[entrypoint]",
        'file_path = "game-data/default.xex"',
        'out_directory_path = "generated/default"',
        "includes = []",
    ]
    for k, v in OPTIONS.items():
        out.append(f"{k} = {str(v).lower()}")
    hints = load_hints()
    if hints:
        out.append("[entrypoint.functions]")
        for a, s in sorted(hints.items()):
            out.append(f"0x{a:08X} = {{ size = 0x{s:X} }}" if s else f"0x{a:08X} = {{}}")
    out.append("")
    (ROOT / "ironbrigade_manifest.toml").write_text("\n".join(out), newline="\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rexglue", default=str(DEFAULT_REXGLUE))
    ap.add_argument("--max-rounds", type=int, default=30)
    ap.add_argument("--no-codegen", action="store_true")
    args = ap.parse_args()
    for rnd in range(args.max_rounds):
        write_manifest()
        if args.no_codegen:
            return 0
        r = subprocess.run([args.rexglue, "codegen", "ironbrigade_manifest.toml"], cwd=ROOT,
                           capture_output=True, text=True, errors="replace")
        log = r.stdout + r.stderr
        (ROOT / "codegen.log").write_text(log)
        if r.returncode == 0:
            print(f"round {rnd}: codegen succeeded")
            return 0
        targets = [int(t, 16) for t in re.findall(r"^\s+(0x[0-9A-Fa-f]+) from 0x[0-9A-Fa-f]+:",
                                                    log, re.M)]
        # ReXGlue v0.11 finds every copy of the millicode helpers (__savegprlr_N and the rest)
        # and refuses a function hint at one: such hints go, with the ones around them (codegen
        # stops at the first; a run is up to 64 entries of 4 or 8 bytes).
        millicode = [int(a, 16) for a in re.findall(
            r"function (0x[0-9A-Fa-f]+) is millicode, which no config entry may replace", log)]
        if millicode:
            hints = load_hints()
            gone = [h for h in hints if any(abs(h - m) <= 0x200 for m in millicode)]
            for h in gone:
                del hints[h]
            save_hints(hints)
            print(f"round {rnd}: {len(gone)} hints at millicode helpers removed")
            continue
        if not targets:
            print(log[-3000:])
            print(f"round {rnd}: codegen failed with nothing to hint")
            return 1
        hints = load_hints()
        added = 0
        for t in targets:
            if t not in hints:
                hints[t] = 0
                added += 1
        if not added:
            print(log[-3000:])
            print(f"round {rnd}: hints already present, stopping")
            return 1
        save_hints(hints)
        print(f"round {rnd}: +{added} hints")
    return 1


if __name__ == "__main__":
    sys.exit(main())
